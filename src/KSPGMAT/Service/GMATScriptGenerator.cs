using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using KSPGMAT.Model;

namespace KSPGMAT.Service {
    public static class GMATScriptGenerator {
        public static string GenerateScript(Vessel vessel, List<MissionStep> steps, string centralBodyOverride = null, Dictionary<string, PropagatorConfig> propConfigsOverride = null) {
            var sb = new StringBuilder();
            var state = GMATStateManager.Current;
            var sc = state.Spacecraft;
            string satName = GMATParameterRegistry.SanitizeGmatIdentifier(sc.Name, "Sat");
            string cBody = !string.IsNullOrEmpty(centralBodyOverride) ? centralBodyOverride : (!string.IsNullOrEmpty(sc.CentralBody) ? sc.CentralBody : "Earth");

            // Ephemeris & Spacecraft Header
            sb.AppendLine("% -------------------------------------------------------------");
            sb.AppendLine("% NASA GMAT Mission Script - Generated by KSP_GMAT Pure C# Engine");
            sb.AppendLine("% -------------------------------------------------------------");
            sb.AppendLine();
            sb.AppendLine($"Create Spacecraft {satName};");
            sb.AppendLine($"{satName}.DateFormat = UTCGregorian;");
            sb.AppendLine($"{satName}.Epoch = '{sc.EpochUtc}';");
            sb.AppendLine($"{satName}.CoordinateSystem = {cBody}MJ2000Eq;");
            sb.AppendLine($"{satName}.DisplayStateType = Cartesian;");
            sb.AppendLine($"{satName}.X = {sc.PosKm.x.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.Y = {sc.PosKm.y.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.Z = {sc.PosKm.z.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.VX = {sc.VelKms.x.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.VY = {sc.VelKms.y.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.VZ = {sc.VelKms.z.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.DryMass = {sc.DryMassKg.ToString("F2", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.DragArea = {sc.DragArea.ToString("F2", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.Cd = {sc.Cd.ToString("F2", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.Cr = {sc.Cr.ToString("F2", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.SRPArea = {sc.SRPArea.ToString("F2", CultureInfo.InvariantCulture)};");
            sb.AppendLine();

            // Tanks
            List<string> tankNames = new List<string>();
            if (state.Tanks != null && state.Tanks.Count > 0) {
                for (int t = 0; t < state.Tanks.Count; t++) {
                    var tk = state.Tanks[t];
                    string tkId = GMATParameterRegistry.SanitizeGmatIdentifier(tk.Id, $"Tank{t}");
                    if (!tankNames.Contains(tkId)) {
                        tankNames.Add(tkId);
                        sb.AppendLine($"Create ChemicalTank {tkId};");
                        sb.AppendLine($"{tkId}.AllowNegativeFuelMass = true;");
                        sb.AppendLine($"{tkId}.FuelMass = {tk.FuelMassKg.ToString("F2", CultureInfo.InvariantCulture)};");
                        double calcVol = Math.Max(tk.VolumeM3, (tk.FuelMassKg / Math.Max(100.0, tk.FuelDensityKgM3)) * 1.1 + 0.1);
                        sb.AppendLine($"{tkId}.Volume = {calcVol.ToString("F3", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{tkId}.FuelDensity = {tk.FuelDensityKgM3.ToString("F2", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{tkId}.PressureModel = '{tk.PressureModel}';");
                    }
                }
            }
            if (tankNames.Count == 0) {
                tankNames.Add("Tank0");
                sb.AppendLine("Create ChemicalTank Tank0;");
                sb.AppendLine("Tank0.AllowNegativeFuelMass = true;");
                sb.AppendLine($"Tank0.FuelMass = {Math.Max(100.0, sc.TotalMassKg - sc.DryMassKg).ToString("F2", CultureInfo.InvariantCulture)};");
                sb.AppendLine("Tank0.Volume = 50.00;");
                sb.AppendLine("Tank0.PressureModel = 'PressureRegulated';");
            }
            sb.AppendLine();

            // Thrusters
            List<string> thrusterNames = new List<string>();
            if (state.Thrusters != null && state.Thrusters.Count > 0) {
                for (int e = 0; e < state.Thrusters.Count; e++) {
                    var thr = state.Thrusters[e];
                    string engId = GMATParameterRegistry.SanitizeGmatIdentifier(thr.Id, $"Engine{e}");
                    if (!thrusterNames.Contains(engId)) {
                        thrusterNames.Add(engId);
                        string boundTk = !string.IsNullOrEmpty(thr.BoundTankId) && tankNames.Contains(thr.BoundTankId) ? thr.BoundTankId : tankNames[0];

                        sb.AppendLine($"Create ChemicalThruster {engId};");
                        sb.AppendLine($"{engId}.CoordinateSystem = Local;");
                        sb.AppendLine($"{engId}.Origin = {cBody};");
                        sb.AppendLine($"{engId}.Axes = VNB;");
                        sb.AppendLine($"{engId}.ThrustDirection1 = {thr.ThrustDirection1.ToString("G", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{engId}.ThrustDirection2 = {thr.ThrustDirection2.ToString("G", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{engId}.ThrustDirection3 = {thr.ThrustDirection3.ToString("G", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{engId}.DecrementMass = {thr.DecrementMass.ToString().ToLower()};");
                        sb.AppendLine($"{engId}.Tank = {{{boundTk}}};");
                        sb.AppendLine($"{engId}.C1 = {(thr.ThrustKN * 1000.0).ToString("F2", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{engId}.K1 = {thr.IspVac.ToString("F2", CultureInfo.InvariantCulture)};");
                    }
                }
            }
            if (thrusterNames.Count == 0) {
                thrusterNames.Add("MainEngine");
                sb.AppendLine("Create ChemicalThruster MainEngine;");
                sb.AppendLine("MainEngine.CoordinateSystem = Local;");
                sb.AppendLine($"MainEngine.Origin = {cBody};");
                sb.AppendLine("MainEngine.Axes = VNB;");
                sb.AppendLine("MainEngine.ThrustDirection1 = 1;");
                sb.AppendLine("MainEngine.ThrustDirection2 = 0;");
                sb.AppendLine("MainEngine.ThrustDirection3 = 0;");
                sb.AppendLine("MainEngine.DecrementMass = true;");
                sb.AppendLine($"MainEngine.Tank = {{{tankNames[0]}}};");
                sb.AppendLine("MainEngine.C1 = 100000.0;");
                sb.AppendLine("MainEngine.K1 = 320.0;");
            }
            sb.AppendLine();

            // Spacecraft Hardware Linkage
            sb.AppendLine($"{satName}.Tanks = {{{string.Join(", ", tankNames.ToArray())}}};");
            sb.AppendLine($"{satName}.Thrusters = {{{string.Join(", ", thrusterNames.ToArray())}}};");
            sb.AppendLine();

            // Finite Burns
            HashSet<string> declaredFiniteBurns = new HashSet<string>();
            if (steps != null) {
                for (int i = 0; i < steps.Count; i++) {
                    var st = steps[i];
                    if (st.type == "FiniteBurn" || st.type == "BeginFiniteBurn") {
                        string fbName = GMATParameterRegistry.SanitizeGmatIdentifier(st.burn_name, $"Finite_{i + 1}");
                        if (!declaredFiniteBurns.Contains(fbName)) {
                            declaredFiniteBurns.Add(fbName);
                            string boundEng = !string.IsNullOrEmpty(st.bound_thruster) && thrusterNames.Contains(st.bound_thruster) ? st.bound_thruster : thrusterNames[0];
                            sb.AppendLine($"Create FiniteBurn {fbName};");
                            sb.AppendLine($"{fbName}.Thrusters = {{{boundEng}}};");
                            sb.AppendLine($"{fbName}.ThrottleLogicAlgorithm = 'MaxNumberOfThrusters';");
                            sb.AppendLine();
                        }
                    }
                }
            }

            // Impulsive Burns
            if (state.Burns != null && state.Burns.Count > 0) {
                for (int ib = 0; ib < state.Burns.Count; ib++) {
                    var imp = state.Burns[ib];
                    if (imp.Type == "ImpulsiveBurn" || !string.IsNullOrEmpty(imp.Name)) {
                        string ibName = GMATParameterRegistry.SanitizeGmatIdentifier(imp.Name, $"Impulsive{ib + 1}");
                        sb.AppendLine($"Create ImpulsiveBurn {ibName};");
                        sb.AppendLine($"{ibName}.CoordinateSystem = Local;");
                        sb.AppendLine($"{ibName}.Origin = {imp.Origin ?? cBody};");
                        sb.AppendLine($"{ibName}.Axes = {imp.Axes ?? "VNB"};");
                        sb.AppendLine($"{ibName}.Element1 = {imp.Element1.ToString("F4", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{ibName}.Element2 = {imp.Element2.ToString("F4", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{ibName}.Element3 = {imp.Element3.ToString("F4", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{ibName}.Isp = {imp.Isp.ToString("F1", CultureInfo.InvariantCulture)};");
                        sb.AppendLine();
                    }
                }
            }

            // Propagators & ForceModels
            var pConfigs = (propConfigsOverride != null && propConfigsOverride.Count > 0) ? propConfigsOverride : GMATParameterRegistry.GetAllPropagatorConfigs();
            if (pConfigs != null && pConfigs.Count > 0) {
                foreach (var kvp in pConfigs) {
                    string pName = kvp.Key;
                    var pCfg = kvp.Value;
                    string fmName = $"{pName}ForceModel";
                    sb.AppendLine($"Create ForceModel {fmName};");
                    sb.AppendLine($"{fmName}.CentralBody = {pCfg.centralBody ?? cBody};");

                    List<string> pmList = new List<string>();
                    if (pCfg.gravityEarth) pmList.Add("Earth");
                    if (pCfg.gravityLuna) pmList.Add("Luna");
                    if (pCfg.gravitySun) pmList.Add("Sun");
                    if (pCfg.gravityJupiter) pmList.Add("Jupiter");
                    if (pCfg.gravityVenus) pmList.Add("Venus");
                    if (pCfg.gravityMars) pmList.Add("Mars");
                    if (pmList.Count > 0) {
                        sb.AppendLine($"{fmName}.PointMasses = {{{string.Join(", ", pmList.ToArray())}}};");
                    }

                    if (pCfg.dragModel != "None" && !string.IsNullOrEmpty(pCfg.dragAtmosphereModel)) {
                        sb.AppendLine($"{fmName}.Drag.AtmosphereModel = '{pCfg.dragAtmosphereModel}';");
                    }
                    if (pCfg.enableSRP) {
                        sb.AppendLine($"{fmName}.SRP = On;");
                    }
                    sb.AppendLine($"Create Propagator {pName};");
                    sb.AppendLine($"{pName}.FM = {fmName};");
                    sb.AppendLine($"{pName}.Type = {pCfg.integratorType ?? "RungeKutta89"};");
                    sb.AppendLine($"{pName}.InitialStepSize = {pCfg.initialStepSize.ToString("F1", CultureInfo.InvariantCulture)};");
                    sb.AppendLine($"{pName}.Accuracy = {pCfg.accuracy.ToString("G", CultureInfo.InvariantCulture)};");
                    sb.AppendLine($"{pName}.MinStep = {pCfg.minStep.ToString("G", CultureInfo.InvariantCulture)};");
                    sb.AppendLine($"{pName}.MaxStep = {pCfg.maxStep.ToString("F1", CultureInfo.InvariantCulture)};");
                    sb.AppendLine();
                }
            } else {
                sb.AppendLine("Create ForceModel LEOPropForceModel;");
                sb.AppendLine($"LEOPropForceModel.CentralBody = {cBody};");
                sb.AppendLine($"LEOPropForceModel.PointMasses = {{{cBody}, Luna, Sun}};");
                sb.AppendLine("Create Propagator LEOProp;");
                sb.AppendLine("LEOProp.FM = LEOPropForceModel;");
                sb.AppendLine("LEOProp.Type = RungeKutta89;");
                sb.AppendLine();
            }

            // Solvers / DifferentialCorrectors
            HashSet<string> declaredSolvers = new HashSet<string>();
            if (state.Solvers != null && state.Solvers.Count > 0) {
                for (int s = 0; s < state.Solvers.Count; s++) {
                    var slv = state.Solvers[s];
                    string sName = GMATParameterRegistry.SanitizeGmatIdentifier(slv.Name, $"DC_{s + 1}");
                    if (!declaredSolvers.Contains(sName)) {
                        declaredSolvers.Add(sName);
                        sb.AppendLine($"Create DifferentialCorrector {sName};");
                        sb.AppendLine($"{sName}.ShowProgress = true;");
                        sb.AppendLine($"{sName}.DerivativeMethod = {slv.DerivativeMethod ?? "ForwardDifference"};");
                        sb.AppendLine($"{sName}.Algorithm = {slv.Algorithm ?? "NewtonRaphson"};");
                        sb.AppendLine($"{sName}.MaximumIterations = {slv.MaxIterations};");
                        sb.AppendLine();
                    }
                }
            }
            if (steps != null) {
                for (int i = 0; i < steps.Count; i++) {
                    var st = steps[i];
                    if ((st.type == "Target" || st.type == "Vary" || st.type == "Achieve") && !string.IsNullOrEmpty(st.dc_name)) {
                        string sName = GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name, "DC");
                        if (!declaredSolvers.Contains(sName)) {
                            declaredSolvers.Add(sName);
                            sb.AppendLine($"Create DifferentialCorrector {sName};");
                            sb.AppendLine($"{sName}.ShowProgress = true;");
                            sb.AppendLine($"{sName}.DerivativeMethod = ForwardDifference;");
                            sb.AppendLine($"{sName}.Algorithm = NewtonRaphson;");
                            sb.AppendLine($"{sName}.MaximumIterations = 50;");
                            sb.AppendLine();
                        }
                    }
                }
            }

            // Variables, Arrays, Strings
            List<string> varNames = new List<string>();
            if (state.Variables != null) {
                foreach (var v in state.Variables) {
                    if (!varNames.Contains(v.Name)) {
                        varNames.Add(v.Name);
                        sb.AppendLine($"Create Variable {v.Name};");
                        sb.AppendLine($"{v.Name} = {v.InitialValue.ToString("G", CultureInfo.InvariantCulture)};");
                    }
                }
            }
            if (steps != null) {
                foreach (var st in steps) {
                    if (st.type == "Vary" && !string.IsNullOrEmpty(st.vary_variable) && !st.vary_variable.Contains(".")) {
                        if (!varNames.Contains(st.vary_variable)) {
                            varNames.Add(st.vary_variable);
                            sb.AppendLine($"Create Variable {st.vary_variable};");
                        }
                    }
                    if (st.type == "FiniteBurn" && st.burn_use_vary_var && !string.IsNullOrEmpty(st.burn_vary_var_name) && !st.burn_vary_var_name.Contains(".")) {
                        if (!varNames.Contains(st.burn_vary_var_name)) {
                            varNames.Add(st.burn_vary_var_name);
                            sb.AppendLine($"Create Variable {st.burn_vary_var_name};");
                        }
                    }
                }
            }
            sb.AppendLine();

            // Trajectory Report File
            sb.AppendLine("Create ReportFile TrajReport;");
            sb.AppendLine("TrajReport.Filename = 'TrajReport.txt';");
            sb.AppendLine("TrajReport.WriteHeaders = false;");
            sb.AppendLine();

            // Mission Sequence Execution Flow
            sb.AppendLine("% -------------------------------------------------------------");
            sb.AppendLine("% GMAT Mission Sequence Execution Control");
            sb.AppendLine("% -------------------------------------------------------------");
            sb.AppendLine("BeginMissionSequence;\n");

            if (steps != null && steps.Count > 0) {
                string currentDC = "DC";
                bool insideTarget = false;

                for (int i = 0; i < steps.Count; i++) {
                    var st = steps[i];
                    string stype = st.type;

                    if (stype == "Propagate") {
                        string pName = !string.IsNullOrEmpty(st.propagator) ? st.propagator : "LEOProp";
                        string stopCond = FormatStopCondition(satName, cBody, st);
                        sb.AppendLine($"% Propagate ({pName})");
                        sb.AppendLine($"Propagate {pName}({satName}) {{{stopCond}}};");
                    }
                    else if (stype == "Target") {
                        currentDC = GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name ?? "DC", "DC");
                        insideTarget = true;
                        sb.AppendLine($"% Target Group ({currentDC})");
                        sb.AppendLine($"Target {currentDC} {{SolveMode = {st.solve_mode ?? "Solve"}, ExitMode = {st.exit_mode ?? "SaveAndContinue"}}};");
                    }
                    else if (stype == "Vary") {
                        string vDC = GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name ?? currentDC, "DC");
                        string vVar = st.vary_variable ?? "burntime";
                        if (vVar.Contains(".")) {
                            string stripped = GMATParameterRegistry.StripCraftPrefix(vVar);
                            vVar = $"{satName}.{stripped}";
                        }
                        double guess = st.vary_initial > 0.0 ? st.vary_initial : 120.0;
                        double pert = st.vary_perturbation > 0.0 ? st.vary_perturbation : 0.0001;
                        double low = st.vary_lower;
                        double up = st.vary_upper > 0.0 ? st.vary_upper : guess * 3.0;
                        double maxStep = st.vary_max_step > 0.0 ? st.vary_max_step : 10.0;
                        sb.AppendLine($"   % Vary ({vVar})");
                        sb.AppendLine($"   Vary {vDC}({vVar} = {guess.ToString("G", CultureInfo.InvariantCulture)}, {{Perturbation = {pert.ToString("G", CultureInfo.InvariantCulture)}, Lower = {low.ToString("G", CultureInfo.InvariantCulture)}, Upper = {up.ToString("G", CultureInfo.InvariantCulture)}, MaxStep = {maxStep.ToString("G", CultureInfo.InvariantCulture)}}});");
                    }
                    else if (stype == "FiniteBurn") {
                        string fbName = GMATParameterRegistry.SanitizeGmatIdentifier(st.burn_name, $"Finite_{i + 1}");
                        string pName = !string.IsNullOrEmpty(st.propagator) ? st.propagator : "LEOProp";
                        string durExpr = st.burn_use_vary_var 
                            ? (!string.IsNullOrEmpty(st.burn_vary_var_name) ? st.burn_vary_var_name : (!string.IsNullOrEmpty(st.duration_str) ? st.duration_str : "burntime")) 
                            : (st.duration > 0 ? st.duration.ToString("F2", CultureInfo.InvariantCulture) : (!string.IsNullOrEmpty(st.duration_str) ? st.duration_str : "120.0"));
                        sb.AppendLine($"   % Finite Burn ({fbName})");
                        sb.AppendLine($"   BeginFiniteBurn {fbName}({satName});");
                        sb.AppendLine($"   Propagate {pName}({satName}) {{{satName}.ElapsedSecs = {durExpr}}};");
                        sb.AppendLine($"   EndFiniteBurn {fbName}({satName});");
                    }
                    else if (stype == "ThrustVectorControl" || stype == "VaryThrustDirection") {
                        string eng = !string.IsNullOrEmpty(st.bound_thruster) && thrusterNames.Contains(st.bound_thruster) ? st.bound_thruster : (thrusterNames.Count > 1 ? thrusterNames[1] : thrusterNames[0]);
                        string tvcDC = GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name ?? currentDC, "DC");
                        sb.AppendLine($"   % Thrust Vector Configuration: {eng} (VNB Axes)");
                        if (st.vary_dir1_enabled && insideTarget) {
                            sb.AppendLine($"   Vary {tvcDC}({satName}.{eng}.ThrustDirection1 = {st.thrust_dir1.ToString("G", CultureInfo.InvariantCulture)}, {{Perturbation = 0.0001, Lower = {st.vary_dir1_lower.ToString("G", CultureInfo.InvariantCulture)}, Upper = {st.vary_dir1_upper.ToString("G", CultureInfo.InvariantCulture)}, MaxStep = {st.vary_dir1_max_step.ToString("G", CultureInfo.InvariantCulture)}}});");
                        } else {
                            sb.AppendLine($"   {satName}.{eng}.ThrustDirection1 = {st.thrust_dir1.ToString("G", CultureInfo.InvariantCulture)};");
                        }
                        if (st.vary_dir2_enabled && insideTarget) {
                            double v2Low = st.vary_dir2_lower != 0 ? st.vary_dir2_lower : -3.0;
                            double v2Up = st.vary_dir2_upper != 0 ? st.vary_dir2_upper : 3.0;
                            double v2Step = st.vary_dir2_max_step > 0 ? st.vary_dir2_max_step : 0.5;
                            sb.AppendLine($"   Vary {tvcDC}({satName}.{eng}.ThrustDirection2 = {st.thrust_dir2.ToString("G", CultureInfo.InvariantCulture)}, {{Perturbation = 0.0001, Lower = {v2Low.ToString("G", CultureInfo.InvariantCulture)}, Upper = {v2Up.ToString("G", CultureInfo.InvariantCulture)}, MaxStep = {v2Step.ToString("G", CultureInfo.InvariantCulture)}}});");
                        } else {
                            sb.AppendLine($"   {satName}.{eng}.ThrustDirection2 = {st.thrust_dir2.ToString("G", CultureInfo.InvariantCulture)};");
                        }
                        if (st.vary_dir3_enabled && insideTarget) {
                            sb.AppendLine($"   Vary {tvcDC}({satName}.{eng}.ThrustDirection3 = {st.thrust_dir3.ToString("G", CultureInfo.InvariantCulture)}, {{Perturbation = 0.0001, Lower = {st.vary_dir3_lower.ToString("G", CultureInfo.InvariantCulture)}, Upper = {st.vary_dir3_upper.ToString("G", CultureInfo.InvariantCulture)}, MaxStep = {st.vary_dir3_max_step.ToString("G", CultureInfo.InvariantCulture)}}});");
                        } else {
                            sb.AppendLine($"   {satName}.{eng}.ThrustDirection3 = {st.thrust_dir3.ToString("G", CultureInfo.InvariantCulture)};");
                        }
                    }
                    else if (stype == "Achieve") {
                        string aDC = GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name ?? currentDC, "DC");
                        string rawGoal = st.achieve_param ?? "Earth.RMAG";
                        string goalParam = GMATParameterRegistry.StripCraftPrefix(rawGoal);
                        if (goalParam.Contains("=")) {
                            goalParam = GMATParameterRegistry.StripCraftPrefix(goalParam.Split('=')[0].Trim());
                        }
                        if (!goalParam.Contains(".")) {
                            string[] craftDirect = new string[] { "TotalMass", "DryMass", "FuelMass", "ElapsedSecs", "ElapsedDays", "A1ModJulian" };
                            bool isCraftDirect = Array.Exists(craftDirect, p => p.Equals(goalParam, StringComparison.OrdinalIgnoreCase));
                            if (!isCraftDirect) {
                                goalParam = $"{cBody}.{goalParam}";
                            }
                        }
                        double val = st.achieve_val;
                        double tol = st.achieve_tolerance > 0 ? st.achieve_tolerance : 0.1;
                        sb.AppendLine($"   % Achieve ({satName}.{goalParam})");
                        sb.AppendLine($"   Achieve {aDC}({satName}.{goalParam} = {val.ToString("G", CultureInfo.InvariantCulture)}, {{Tolerance = {tol.ToString("G", CultureInfo.InvariantCulture)}}});");
                    }
                    else if (stype == "EndTarget") {
                        insideTarget = false;
                        sb.AppendLine($"EndTarget;  % For {currentDC}");
                    }
                    else if (stype == "ImpulsiveBurn" || stype == "Maneuver") {
                        string bName = GMATParameterRegistry.SanitizeGmatIdentifier(st.burn_name ?? st.label, "Burn1");
                        sb.AppendLine($"% Impulsive Maneuver ({bName})");
                        sb.AppendLine($"Maneuver {bName}({satName});");
                    }
                    else if (stype == "Equation" || stype == "Set") {
                        string vName = st.variable ?? "";
                        if (string.IsNullOrWhiteSpace(vName)) continue;
                        if (vName.Contains(".ThrustDirection")) continue; // Skip orphan ThrustDirection assignment steps
                        if (vName.Contains(".")) {
                            string stripped = GMATParameterRegistry.StripCraftPrefix(vName);
                            vName = $"{satName}.{stripped}";
                        }
                        sb.AppendLine($"{vName} = {st.expression};");
                    }
                    else if (stype == "Report") {
                        if (!string.IsNullOrWhiteSpace(st.expression)) {
                            string sub = !string.IsNullOrEmpty(st.subscriber_name) ? st.subscriber_name : "TrajReport";
                            sb.AppendLine($"Report {sub} {st.expression};");
                        }
                    }
                }
            } else {
                sb.AppendLine($"Propagate LEOProp({satName}) {{{satName}.ElapsedSecs = 12000.0}};");
            }

            // Final Native Trajectory and Orbital Elements Report
            sb.AppendLine("% Trajectory & Orbital Parameters Report");
            sb.AppendLine($"Report TrajReport {satName}.ElapsedSecs {satName}.X {satName}.Y {satName}.Z {satName}.VX {satName}.VY {satName}.VZ {satName}.{cBody}.Altitude {satName}.SMA {satName}.ECC {satName}.INC {satName}.RAAN {satName}.AOP {satName}.TA {satName}.TotalMass;");

            return sb.ToString();
        }

        private static string FormatStopCondition(string satName, string centralBody, MissionStep st) {
            string rawCond = st.stop_type ?? "Time";
            string cond = GMATParameterRegistry.StripCraftPrefix(rawCond).Trim();

            // 1. If condition already contains an explicit '=', e.g. "Earth.Altitude = 200" or "ElapsedSecs = 3600"
            if (cond.Contains("=")) {
                var p = cond.Split('=');
                string lhs = GMATParameterRegistry.StripCraftPrefix(p[0].Trim());
                string rhs = p[1].Trim();
                if (!lhs.Contains(".") && !lhs.StartsWith("Elapsed", StringComparison.OrdinalIgnoreCase) && !lhs.StartsWith("TA", StringComparison.OrdinalIgnoreCase)) {
                    lhs = $"{centralBody}.{lhs}";
                }
                return $"{satName}.{lhs} = {rhs}";
            }

            // 2. GMAT Built-in Extrema Events (No '=' sign required by GMAT syntax)
            // e.g. Apoapsis, Periapsis, Node, AN, DN
            string[] extremaKeywords = new string[] { "Apoapsis", "Periapsis", "Node", "AN", "DN" };
            foreach (var kw in extremaKeywords) {
                if (cond.Equals(kw, StringComparison.OrdinalIgnoreCase)) {
                    return $"{satName}.{centralBody}.{kw}";
                }
                if (cond.EndsWith("." + kw, StringComparison.OrdinalIgnoreCase)) {
                    return $"{satName}.{cond}";
                }
            }

            // 3. Elapsed Time Stop Conditions
            if (cond.Equals("Time", StringComparison.OrdinalIgnoreCase) || cond.Equals("ElapsedSecs", StringComparison.OrdinalIgnoreCase) || cond.EndsWith(".ElapsedSecs", StringComparison.OrdinalIgnoreCase)) {
                string durVal = !string.IsNullOrEmpty(st.duration_str) ? st.duration_str : (st.duration > 0 ? st.duration.ToString("G", CultureInfo.InvariantCulture) : (!string.IsNullOrEmpty(st.target_val_str) ? st.target_val_str : (st.target_val > 0 ? st.target_val.ToString("G", CultureInfo.InvariantCulture) : "3600.0")));
                return $"{satName}.ElapsedSecs = {durVal}";
            }
            if (cond.Equals("Days", StringComparison.OrdinalIgnoreCase) || cond.Equals("ElapsedDays", StringComparison.OrdinalIgnoreCase) || cond.EndsWith(".ElapsedDays", StringComparison.OrdinalIgnoreCase)) {
                string durStr = !string.IsNullOrEmpty(st.duration_str) ? st.duration_str : (st.duration > 0 ? (st.duration / 86400.0).ToString("G", CultureInfo.InvariantCulture) : (!string.IsNullOrEmpty(st.target_val_str) ? st.target_val_str : (st.target_val > 0 ? st.target_val.ToString("G", CultureInfo.InvariantCulture) : "1.0")));
                return $"{satName}.ElapsedDays = {durStr}";
            }

            // 4. Value-based Numerical Stop Conditions (e.g. Altitude, RMAG, Latitude, TA, RAAN, AOP, FPA, etc.)
            string rhsVal = !string.IsNullOrEmpty(st.target_val_str) ? st.target_val_str : st.target_val.ToString("G", CultureInfo.InvariantCulture);
            if (!cond.Contains(".") && !cond.StartsWith("Elapsed", StringComparison.OrdinalIgnoreCase)) {
                cond = $"{centralBody}.{cond}";
            }
            return $"{satName}.{cond} = {rhsVal}";
        }
    }
