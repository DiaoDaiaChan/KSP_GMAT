using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using KSPGMAT.Model;

namespace KSPGMAT.Service {
    public static class GMATScriptGenerator {
        public static string GenerateScript(Vessel vessel, List<MissionStep> steps, string centralBodyOverride = null, Dictionary<string, PropagatorConfig> propConfigsOverride = null) {
            var sb = new StringBuilder();
            var state = GMATStateManager.Current;
            state.ValidateAndSanitizeState(propConfigsOverride, steps);
            var sc = state.Spacecraft;
            // 基线 1.3: 航天器标准名称必须经 SSOT 构造器获取，杜绝硬编码 "Sat"
            string satName = state.GetSpacecraftName();
            string cBody = !string.IsNullOrEmpty(centralBodyOverride) ? centralBodyOverride : (!string.IsNullOrEmpty(sc.CentralBody) ? sc.CentralBody : "Earth");

            // Ephemeris & Spacecraft Header
            sb.AppendLine("% -------------------------------------------------------------");
            sb.AppendLine("% NASA GMAT Mission Script - Generated by KSP_GMAT Pure C# Engine");
            sb.AppendLine("% -------------------------------------------------------------");
            if (GMATClient.HasFullSpiceEphemeris) {
                string spkPath = GMATClient.DetectedSpiceKernelPath;
                string kernelName = GMATClient.DetectedSpiceKernelName;
                sb.AppendLine($"% NASA JPL SPICE Ephemeris: {kernelName} (High-Precision Numerical Ephemeris DE440/DE430)");
                sb.AppendLine("GMAT SolarSystem.EphemerisSource = 'SPICE';");
                if (!string.IsNullOrEmpty(spkPath) && File.Exists(spkPath)) {
                    string safeSpk = spkPath.Replace("\\", "/");
                    sb.AppendLine($"GMAT SolarSystem.SPKFilename = '{safeSpk}';");
                }
                sb.AppendLine("GMAT Mars.NAIFId = 4;");
                sb.AppendLine("GMAT Jupiter.NAIFId = 5;");
                sb.AppendLine("GMAT Saturn.NAIFId = 6;");
                sb.AppendLine("GMAT Uranus.NAIFId = 7;");
                sb.AppendLine("GMAT Neptune.NAIFId = 8;");
                sb.AppendLine("GMAT Pluto.NAIFId = 9;");
            }
            sb.AppendLine();
            sb.AppendLine($"Create Spacecraft {satName};");
            sb.AppendLine($"{satName}.DateFormat = UTCGregorian;");
            sb.AppendLine($"{satName}.Epoch = '{GMATClient.FormatGmatSafeEpochString(sc.EpochUtc)}';");
            sb.AppendLine($"{satName}.CoordinateSystem = {cBody}MJ2000Eq;");
            sb.AppendLine($"{satName}.DisplayStateType = Cartesian;");
            sb.AppendLine($"{satName}.X = {sc.PosKm.x.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.Y = {sc.PosKm.y.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.Z = {sc.PosKm.z.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.VX = {sc.VelKms.x.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.VY = {sc.VelKms.y.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.VZ = {sc.VelKms.z.ToString("F6", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.DryMass = {sc.DryMassKg.ToString("G", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.DragArea = {sc.DragArea.ToString("G", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.Cd = {sc.Cd.ToString("G", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.Cr = {sc.Cr.ToString("G", CultureInfo.InvariantCulture)};");
            sb.AppendLine($"{satName}.SRPArea = {sc.SRPArea.ToString("G", CultureInfo.InvariantCulture)};");
            sb.AppendLine();

            // Tanks
            List<string> tankNames = new List<string>();
            if (state.Tanks != null && state.Tanks.Count > 0) {
                for (int t = 0; t < state.Tanks.Count; t++) {
                    var tk = state.Tanks[t];
                    string tkId = GMATParameterRegistry.SanitizeGmatIdentifier(tk.Id, $"Tank{t}");
                    if (!tankNames.Contains(tkId)) {
                        tankNames.Add(tkId);
                        sb.AppendLine($"Create ChemicalTank {tkId};");
                        sb.AppendLine($"{tkId}.AllowNegativeFuelMass = true;");
                        sb.AppendLine($"{tkId}.FuelMass = {tk.FuelMassKg.ToString("G", CultureInfo.InvariantCulture)};");
                        double calcVol = Math.Max(tk.VolumeM3, (tk.FuelMassKg / Math.Max(100.0, tk.FuelDensityKgM3)) * 1.1 + 0.1);
                        sb.AppendLine($"{tkId}.Volume = {calcVol.ToString("G", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{tkId}.FuelDensity = {tk.FuelDensityKgM3.ToString("G", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{tkId}.PressureModel = '{tk.PressureModel}';");
                    }
                }
            }
            if (tankNames.Count == 0) {
                tankNames.Add("Tank0");
                sb.AppendLine("Create ChemicalTank Tank0;");
                sb.AppendLine("Tank0.AllowNegativeFuelMass = true;");
                sb.AppendLine($"Tank0.FuelMass = {Math.Max(100.0, sc.TotalMassKg - sc.DryMassKg).ToString("G", CultureInfo.InvariantCulture)};");
                sb.AppendLine("Tank0.Volume = 50.00;");
                sb.AppendLine("Tank0.PressureModel = 'PressureRegulated';");
            }
            sb.AppendLine();

            // Thrusters
            List<string> thrusterNames = new List<string>();
            if (state.Thrusters != null && state.Thrusters.Count > 0) {
                for (int e = 0; e < state.Thrusters.Count; e++) {
                    var thr = state.Thrusters[e];
                    string engId = GMATParameterRegistry.SanitizeGmatIdentifier(thr.Id, $"Engine{e}");
                    if (!thrusterNames.Contains(engId)) {
                        thrusterNames.Add(engId);
                        string boundTk = !string.IsNullOrEmpty(thr.BoundTankId) && tankNames.Contains(thr.BoundTankId) ? thr.BoundTankId : tankNames[0];

                        sb.AppendLine($"Create ChemicalThruster {engId};");
                        sb.AppendLine($"{engId}.CoordinateSystem = Local;");
                        sb.AppendLine($"{engId}.Origin = {cBody};");
                        sb.AppendLine($"{engId}.Axes = VNB;");
                        sb.AppendLine($"{engId}.ThrustDirection1 = {thr.ThrustDirection1.ToString("G", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{engId}.ThrustDirection2 = {thr.ThrustDirection2.ToString("G", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{engId}.ThrustDirection3 = {thr.ThrustDirection3.ToString("G", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{engId}.DecrementMass = {thr.DecrementMass.ToString().ToLower()};");
                        sb.AppendLine($"{engId}.Tank = {{{boundTk}}};");
                        sb.AppendLine($"{engId}.C1 = {(thr.ThrustKN * 1000.0).ToString("G", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{engId}.K1 = {thr.IspVac.ToString("G", CultureInfo.InvariantCulture)};");
                    }
                }
            }
            if (thrusterNames.Count == 0) {
                thrusterNames.Add("MainEngine");
                sb.AppendLine("Create ChemicalThruster MainEngine;");
                sb.AppendLine("MainEngine.CoordinateSystem = Local;");
                sb.AppendLine($"MainEngine.Origin = {cBody};");
                sb.AppendLine("MainEngine.Axes = VNB;");
                sb.AppendLine("MainEngine.ThrustDirection1 = 1;");
                sb.AppendLine("MainEngine.ThrustDirection2 = 0;");
                sb.AppendLine("MainEngine.ThrustDirection3 = 0;");
                sb.AppendLine("MainEngine.DecrementMass = true;");
                sb.AppendLine($"MainEngine.Tank = {{{tankNames[0]}}};");
                sb.AppendLine("MainEngine.C1 = 100000.0;");
                sb.AppendLine("MainEngine.K1 = 320.0;");
            }
            sb.AppendLine();

            // Spacecraft Hardware Linkage
            sb.AppendLine($"{satName}.Tanks = {{{string.Join(", ", tankNames.ToArray())}}};");
            sb.AppendLine($"{satName}.Thrusters = {{{string.Join(", ", thrusterNames.ToArray())}}};");
            sb.AppendLine();

            // Finite Burns
            HashSet<string> declaredFiniteBurns = new HashSet<string>();
            if (steps != null) {
                for (int i = 0; i < steps.Count; i++) {
                    var st = steps[i];
                    if (st.type == "FiniteBurn" || st.type == "BeginFiniteBurn") {
                        string fbName = GMATParameterRegistry.SanitizeGmatIdentifier(st.burn_name, $"Finite_{i + 1}");
                        if (!declaredFiniteBurns.Contains(fbName)) {
                            declaredFiniteBurns.Add(fbName);
                            string boundEng = !string.IsNullOrEmpty(st.bound_thruster) && thrusterNames.Contains(st.bound_thruster) ? st.bound_thruster : thrusterNames[0];
                            sb.AppendLine($"Create FiniteBurn {fbName};");
                            sb.AppendLine($"{fbName}.Thrusters = {{{boundEng}}};");
                            sb.AppendLine($"{fbName}.ThrottleLogicAlgorithm = 'MaxNumberOfThrusters';");
                            sb.AppendLine();
                        }
                    }
                }
            }

            // Impulsive Burns
            if (state.Burns != null && state.Burns.Count > 0) {
                for (int ib = 0; ib < state.Burns.Count; ib++) {
                    var imp = state.Burns[ib];
                    if (imp.Type == "ImpulsiveBurn" || !string.IsNullOrEmpty(imp.Name)) {
                        string ibName = GMATParameterRegistry.SanitizeGmatIdentifier(imp.Name, $"Impulsive{ib + 1}");
                        sb.AppendLine($"Create ImpulsiveBurn {ibName};");
                        sb.AppendLine($"{ibName}.CoordinateSystem = Local;");
                        sb.AppendLine($"{ibName}.Origin = {imp.Origin ?? cBody};");
                        sb.AppendLine($"{ibName}.Axes = {imp.Axes ?? "VNB"};");
                        sb.AppendLine($"{ibName}.Element1 = {imp.Element1.ToString("F4", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{ibName}.Element2 = {imp.Element2.ToString("F4", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{ibName}.Element3 = {imp.Element3.ToString("F4", CultureInfo.InvariantCulture)};");
                        sb.AppendLine($"{ibName}.Isp = {imp.Isp.ToString("F1", CultureInfo.InvariantCulture)};");
                        sb.AppendLine();
                    }
                }
            }

            // Propagators & ForceModels
            var pConfigs = (propConfigsOverride != null && propConfigsOverride.Count > 0) ? propConfigsOverride : GMATParameterRegistry.GetAllPropagatorConfigs();
            if (pConfigs != null && pConfigs.Count > 0) {
                foreach (var kvp in pConfigs) {
                    string pName = kvp.Key;
                    var pCfg = kvp.Value;
                    string fmName = $"{pName}ForceModel";
                    sb.AppendLine($"Create ForceModel {fmName};");
                    sb.AppendLine($"{fmName}.CentralBody = {pCfg.centralBody ?? cBody};");

                    List<string> pmList = new List<string>();
                    if (pCfg.gravityEarth) pmList.Add("Earth");
                    if (pCfg.gravityLuna) pmList.Add("Luna");
                    if (pCfg.gravitySun) pmList.Add("Sun");
                    if (pCfg.gravityJupiter) pmList.Add("Jupiter");
                    if (pCfg.gravityVenus) pmList.Add("Venus");
                    if (pCfg.gravityMars) pmList.Add("Mars");
                    if (pmList.Count > 0) {
                        sb.AppendLine($"{fmName}.PointMasses = {{{string.Join(", ", pmList.ToArray())}}};");
                    }

                    if (pCfg.dragModel != "None" && !string.IsNullOrEmpty(pCfg.dragAtmosphereModel)) {
                        sb.AppendLine($"{fmName}.Drag.AtmosphereModel = '{pCfg.dragAtmosphereModel}';");
                    }
                    if (pCfg.enableSRP) {
                        sb.AppendLine($"{fmName}.SRP = On;");
                    }
                    sb.AppendLine($"Create Propagator {pName};");
                    sb.AppendLine($"{pName}.FM = {fmName};");
                    sb.AppendLine($"{pName}.Type = {pCfg.integratorType ?? "RungeKutta89"};");
                    sb.AppendLine($"{pName}.InitialStepSize = {pCfg.initialStepSize.ToString("F1", CultureInfo.InvariantCulture)};");
                    sb.AppendLine($"{pName}.Accuracy = {pCfg.accuracy.ToString("G", CultureInfo.InvariantCulture)};");
                    sb.AppendLine($"{pName}.MinStep = {pCfg.minStep.ToString("G", CultureInfo.InvariantCulture)};");
                    sb.AppendLine($"{pName}.MaxStep = {pCfg.maxStep.ToString("F1", CultureInfo.InvariantCulture)};");
                    sb.AppendLine();
                }
            } else {
                sb.AppendLine("Create ForceModel LEOPropForceModel;");
                sb.AppendLine($"LEOPropForceModel.CentralBody = {cBody};");
                sb.AppendLine($"LEOPropForceModel.PointMasses = {{{cBody}, Luna, Sun}};");
                sb.AppendLine("Create Propagator LEOProp;");
                sb.AppendLine("LEOProp.FM = LEOPropForceModel;");
                sb.AppendLine("LEOProp.Type = RungeKutta89;");
                sb.AppendLine($"LEOProp.Accuracy = {GMATDefaults.Propagator.Accuracy.ToString("G", CultureInfo.InvariantCulture)};");
                sb.AppendLine();
            }

            // Solvers / DifferentialCorrectors & Optimizers
            HashSet<string> declaredSolvers = new HashSet<string>();
            HashSet<string> declaredOptimizers = new HashSet<string>();

            if (state.Solvers != null && state.Solvers.Count > 0) {
                for (int s = 0; s < state.Solvers.Count; s++) {
                    var slv = state.Solvers[s];
                    string sName = GMATParameterRegistry.SanitizeGmatIdentifier(slv.Name, $"DC_{s + 1}");
                    if (!declaredSolvers.Contains(sName)) {
                        declaredSolvers.Add(sName);
                        sb.AppendLine($"Create DifferentialCorrector {sName};");
                        sb.AppendLine($"{sName}.ShowProgress = true;");
                        sb.AppendLine($"{sName}.DerivativeMethod = {slv.DerivativeMethod ?? "ForwardDifference"};");
                        sb.AppendLine($"{sName}.Algorithm = {slv.Algorithm ?? "NewtonRaphson"};");
                        sb.AppendLine($"{sName}.MaximumIterations = {slv.MaxIterations};");
                        sb.AppendLine();
                    }
                }
            }
            if (steps != null) {
                for (int i = 0; i < steps.Count; i++) {
                    var st = steps[i];
                    if (!string.IsNullOrEmpty(st.dc_name)) {
                        string sName = GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name, "DC");
                        if (!declaredSolvers.Contains(sName)) {
                            declaredSolvers.Add(sName);
                            sb.AppendLine($"Create DifferentialCorrector {sName};");
                            sb.AppendLine($"{sName}.ShowProgress = true;");
                            sb.AppendLine($"{sName}.DerivativeMethod = ForwardDifference;");
                            sb.AppendLine($"{sName}.Algorithm = NewtonRaphson;");
                            sb.AppendLine($"{sName}.MaximumIterations = 50;");
                            sb.AppendLine();
                        }
                    }
                    if (st.type == "Optimize" || st.type == "Minimize" || st.type == "NonlinearConstraint") {
                        string optName = GMATParameterRegistry.SanitizeGmatIdentifier(!string.IsNullOrEmpty(st.optimizer_name) ? st.optimizer_name : "Yukon1", "Yukon1");
                        if (!declaredOptimizers.Contains(optName)) {
                            declaredOptimizers.Add(optName);
                            sb.AppendLine($"Create Yukon {optName};");
                            sb.AppendLine($"{optName}.ShowProgress = true;");
                            sb.AppendLine($"{optName}.ReportStyle = Normal;");
                            sb.AppendLine($"{optName}.MaximumIterations = 200;");
                            sb.AppendLine($"{optName}.FeasibilityTolerance = 0.0001;");
                            sb.AppendLine($"{optName}.OptimalityTolerance = 0.0001;");
                            sb.AppendLine();
                        }
                    }
                }
            }

            // Variables, Arrays, Strings
            List<string> varNames = new List<string>();
            if (state.Variables != null) {
                foreach (var v in state.Variables) {
                    if (!varNames.Contains(v.Name)) {
                        varNames.Add(v.Name);
                        sb.AppendLine($"Create Variable {v.Name};");
                        sb.AppendLine($"{v.Name} = {v.InitialValue.ToString("G", CultureInfo.InvariantCulture)};");
                    }
                }
            }
            if (steps != null) {
                foreach (var st in steps) {
                    if (st.type == "Vary" && !string.IsNullOrEmpty(st.vary_variable) && !st.vary_variable.Contains(".")) {
                        if (!varNames.Contains(st.vary_variable)) {
                            varNames.Add(st.vary_variable);
                            sb.AppendLine($"Create Variable {st.vary_variable};");
                        }
                    }
                    if (st.type == "FiniteBurn" && st.burn_use_vary_var && !string.IsNullOrEmpty(st.burn_vary_var_name) && !st.burn_vary_var_name.Contains(".")) {
                        if (!varNames.Contains(st.burn_vary_var_name)) {
                            varNames.Add(st.burn_vary_var_name);
                            sb.AppendLine($"Create Variable {st.burn_vary_var_name};");
                        }
                    }
                }
            }
            sb.AppendLine();

            // Trajectory Report File
            sb.AppendLine("Create ReportFile TrajReport;");
            sb.AppendLine("TrajReport.Filename = 'TrajReport.txt';");
            sb.AppendLine("TrajReport.WriteHeaders = false;");

            // Custom Step Report Files
            List<string> createdReportFiles = new List<string>();
            if (steps != null) {
                for (int i = 0; i < steps.Count; i++) {
                    var st = steps[i];
                    if (st.type == "Report") {
                        string sub = GMATParameterRegistry.SanitizeGmatIdentifier(!string.IsNullOrEmpty(st.subscriber_name) ? st.subscriber_name : $"StepReport_{i + 1}", $"StepReport_{i + 1}");
                        st.subscriber_name = sub;
                        if (!createdReportFiles.Contains(sub) && !sub.Equals("TrajReport", StringComparison.OrdinalIgnoreCase)) {
                            createdReportFiles.Add(sub);
                            sb.AppendLine($"Create ReportFile {sub};");
                            sb.AppendLine($"{sub}.Filename = '{sub}.txt';");
                            sb.AppendLine($"{sub}.WriteHeaders = false;");
                        }
                    }
                }
            }
            sb.AppendLine();

            // Mission Sequence Execution Flow
            sb.AppendLine("% -------------------------------------------------------------");
            sb.AppendLine("% GMAT Mission Sequence Execution Control");
            sb.AppendLine("% -------------------------------------------------------------");
            sb.AppendLine("BeginMissionSequence;\n");

            // Initial State Epoch Report
            sb.AppendLine("% Initial State Epoch Report (T=0)");
            sb.AppendLine($"Report TrajReport {satName}.ElapsedSecs {satName}.X {satName}.Y {satName}.Z {satName}.VX {satName}.VY {satName}.VZ {satName}.{cBody}.Altitude {satName}.SMA {satName}.ECC {satName}.INC {satName}.RAAN {satName}.AOP {satName}.TA {satName}.TotalMass;");

            if (steps != null && steps.Count > 0) {
                string currentDC = "DC";
                bool insideTarget = false;

                for (int i = 0; i < steps.Count; i++) {
                    var st = steps[i];
                    string stype = st.type;

                    if (stype == "Propagate") {
                        string pName = !string.IsNullOrEmpty(st.propagator) ? st.propagator : "LEOProp";
                        string stopCond = FormatStopCondition(satName, cBody, st);
                        string backMod = st.is_backwards ? " Backwards" : "";
                        sb.AppendLine($"% Propagate{backMod} ({pName})");
                        sb.AppendLine($"Propagate{backMod} {pName}({satName}) {{{stopCond}}};");
                        if (!insideTarget) {
                            sb.AppendLine($"Report TrajReport {satName}.ElapsedSecs {satName}.X {satName}.Y {satName}.Z {satName}.VX {satName}.VY {satName}.VZ {satName}.{cBody}.Altitude {satName}.SMA {satName}.ECC {satName}.INC {satName}.RAAN {satName}.AOP {satName}.TA {satName}.TotalMass;");
                        }
                    }
                    else if (stype == "Target") {
                        currentDC = GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name ?? "DC", "DC");
                        insideTarget = true;
                        sb.AppendLine($"% Target Group ({currentDC})");
                        sb.AppendLine($"Target {currentDC} {{SolveMode = {st.solve_mode ?? "Solve"}, ExitMode = {st.exit_mode ?? "SaveAndContinue"}}};");
                    }
                    else if (stype == "Vary") {
                        string vDC = (insideTarget && !string.IsNullOrEmpty(currentDC)) ? currentDC : GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name ?? currentDC, "DC");
                        string vVar = st.vary_variable ?? "";
                        if (vVar.Contains(".")) {
                            string stripped = GMATParameterRegistry.StripCraftPrefix(vVar);
                            vVar = $"{satName}.{stripped}";
                        }
                        string initExpr = !string.IsNullOrEmpty(st.vary_initial_str) ? st.vary_initial_str : st.vary_initial.ToString("G", CultureInfo.InvariantCulture);
                        string pertExpr = !string.IsNullOrEmpty(st.vary_perturbation_str) ? st.vary_perturbation_str : (st.vary_perturbation > 0.0 ? st.vary_perturbation.ToString("G", CultureInfo.InvariantCulture) : "0.0001");
                        string lowExpr = !string.IsNullOrEmpty(st.vary_lower_str) ? st.vary_lower_str : st.vary_lower.ToString("G", CultureInfo.InvariantCulture);
                        string upExpr = !string.IsNullOrEmpty(st.vary_upper_str) ? st.vary_upper_str : st.vary_upper.ToString("G", CultureInfo.InvariantCulture);
                        string maxStepExpr = !string.IsNullOrEmpty(st.vary_max_step_str) ? st.vary_max_step_str : (st.vary_max_step > 0.0 ? st.vary_max_step.ToString("G", CultureInfo.InvariantCulture) : "10");
                        sb.AppendLine($"   % Vary ({vVar})");
                        sb.AppendLine($"   Vary {vDC}({vVar} = {initExpr}, {{Perturbation = {pertExpr}, Lower = {lowExpr}, Upper = {upExpr}, MaxStep = {maxStepExpr}}});");
                    }
                    else if (stype == "FiniteBurn") {
                        string fbName = GMATParameterRegistry.SanitizeGmatIdentifier(st.burn_name, $"Finite_{i + 1}");
                        string pName = !string.IsNullOrEmpty(st.propagator) ? st.propagator : "LEOProp";
                        string durExpr = st.burn_use_vary_var 
                            ? (st.burn_vary_var_name ?? "") 
                            : (!string.IsNullOrEmpty(st.duration_str) ? st.duration_str : st.duration.ToString("G", CultureInfo.InvariantCulture));
                        sb.AppendLine($"   % Finite Burn ({fbName})");
                        sb.AppendLine($"   Report TrajReport {satName}.ElapsedSecs {satName}.X {satName}.Y {satName}.Z {satName}.VX {satName}.VY {satName}.VZ {satName}.{cBody}.Altitude {satName}.SMA {satName}.ECC {satName}.INC {satName}.RAAN {satName}.AOP {satName}.TA {satName}.TotalMass;");
                        sb.AppendLine($"   BeginFiniteBurn {fbName}({satName});");
                        sb.AppendLine($"   Propagate {pName}({satName}) {{{satName}.ElapsedSecs = {durExpr}}};");
                        sb.AppendLine($"   EndFiniteBurn {fbName}({satName});");
                        sb.AppendLine($"   Report TrajReport {satName}.ElapsedSecs {satName}.X {satName}.Y {satName}.Z {satName}.VX {satName}.VY {satName}.VZ {satName}.{cBody}.Altitude {satName}.SMA {satName}.ECC {satName}.INC {satName}.RAAN {satName}.AOP {satName}.TA {satName}.TotalMass;");
                    }
                    else if (stype == "ThrustVectorControl" || stype == "VaryThrustDirection") {
                        string eng = !string.IsNullOrEmpty(st.bound_thruster) && thrusterNames.Contains(st.bound_thruster) ? st.bound_thruster : (thrusterNames.Count > 1 ? thrusterNames[1] : thrusterNames[0]);
                        string tvcDC = (insideTarget && !string.IsNullOrEmpty(currentDC)) ? currentDC : GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name ?? currentDC, "DC");
                        sb.AppendLine($"   % Thrust Vector Configuration: {eng} (VNB Axes)");
                        if (st.vary_dir1_enabled && insideTarget) {
                            sb.AppendLine($"   Vary {tvcDC}({satName}.{eng}.ThrustDirection1 = {st.thrust_dir1.ToString("G", CultureInfo.InvariantCulture)}, {{Perturbation = 0.0001, Lower = {st.vary_dir1_lower.ToString("G", CultureInfo.InvariantCulture)}, Upper = {st.vary_dir1_upper.ToString("G", CultureInfo.InvariantCulture)}, MaxStep = {st.vary_dir1_max_step.ToString("G", CultureInfo.InvariantCulture)}}});");
                        } else {
                            sb.AppendLine($"   {satName}.{eng}.ThrustDirection1 = {st.thrust_dir1.ToString("G", CultureInfo.InvariantCulture)};");
                        }
                        if (st.vary_dir2_enabled && insideTarget) {
                            sb.AppendLine($"   Vary {tvcDC}({satName}.{eng}.ThrustDirection2 = {st.thrust_dir2.ToString("G", CultureInfo.InvariantCulture)}, {{Perturbation = 0.0001, Lower = {st.vary_dir2_lower.ToString("G", CultureInfo.InvariantCulture)}, Upper = {st.vary_dir2_upper.ToString("G", CultureInfo.InvariantCulture)}, MaxStep = {st.vary_dir2_max_step.ToString("G", CultureInfo.InvariantCulture)}}});");
                        } else {
                            sb.AppendLine($"   {satName}.{eng}.ThrustDirection2 = {st.thrust_dir2.ToString("G", CultureInfo.InvariantCulture)};");
                        }
                        if (st.vary_dir3_enabled && insideTarget) {
                            sb.AppendLine($"   Vary {tvcDC}({satName}.{eng}.ThrustDirection3 = {st.thrust_dir3.ToString("G", CultureInfo.InvariantCulture)}, {{Perturbation = 0.0001, Lower = {st.vary_dir3_lower.ToString("G", CultureInfo.InvariantCulture)}, Upper = {st.vary_dir3_upper.ToString("G", CultureInfo.InvariantCulture)}, MaxStep = {st.vary_dir3_max_step.ToString("G", CultureInfo.InvariantCulture)}}});");
                        } else {
                            sb.AppendLine($"   {satName}.{eng}.ThrustDirection3 = {st.thrust_dir3.ToString("G", CultureInfo.InvariantCulture)};");
                        }
                    }
                    else if (stype == "Achieve") {
                        string aDC = (insideTarget && !string.IsNullOrEmpty(currentDC)) ? currentDC : GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name ?? currentDC, "DC");
                        string rawGoal = st.achieve_param ?? "";
                        string goalParam = GMATParameterRegistry.StripCraftPrefix(rawGoal);
                        if (goalParam.Contains("=")) {
                            goalParam = GMATParameterRegistry.StripCraftPrefix(goalParam.Split('=')[0].Trim());
                        }
                        if (!goalParam.Contains(".")) {
                            string[] craftDirect = new string[] { 
                                "TotalMass", "DryMass", "FuelMass", "ElapsedSecs", "ElapsedDays", "A1ModJulian",
                                "SMA", "ECC", "INC", "RAAN", "AOP", "TA", "EA", "MA", "RadPer", "RadApo"
                            };
                            bool isCraftDirect = Array.Exists(craftDirect, p => p.Equals(goalParam, StringComparison.OrdinalIgnoreCase));
                            if (!isCraftDirect) {
                                goalParam = $"{cBody}.{goalParam}";
                            }
                        }
                        string valExpr = !string.IsNullOrEmpty(st.achieve_val_str) ? st.achieve_val_str : st.achieve_val.ToString("G", CultureInfo.InvariantCulture);
                        string tolExpr = !string.IsNullOrEmpty(st.achieve_tolerance_str) ? st.achieve_tolerance_str : (st.achieve_tolerance > 0.0 ? st.achieve_tolerance.ToString("G", CultureInfo.InvariantCulture) : "0.1");
                        sb.AppendLine($"   % Achieve ({satName}.{goalParam})");
                        sb.AppendLine($"   Achieve {aDC}({satName}.{goalParam} = {valExpr}, {{Tolerance = {tolExpr}}});");
                    }
                    else if (stype == "EndTarget") {
                        insideTarget = false;
                        sb.AppendLine($"EndTarget;  % For {currentDC}");
                        sb.AppendLine($"Report TrajReport {satName}.ElapsedSecs {satName}.X {satName}.Y {satName}.Z {satName}.VX {satName}.VY {satName}.VZ {satName}.{cBody}.Altitude {satName}.SMA {satName}.ECC {satName}.INC {satName}.RAAN {satName}.AOP {satName}.TA {satName}.TotalMass;");
                    }
                    else if (stype == "ImpulsiveBurn" || stype == "Maneuver") {
                        string bName = GMATParameterRegistry.SanitizeGmatIdentifier(st.burn_name ?? st.label, "Burn1");
                        sb.AppendLine($"% Impulsive Maneuver ({bName})");
                        sb.AppendLine($"Report TrajReport {satName}.ElapsedSecs {satName}.X {satName}.Y {satName}.Z {satName}.VX {satName}.VY {satName}.VZ {satName}.{cBody}.Altitude {satName}.SMA {satName}.ECC {satName}.INC {satName}.RAAN {satName}.AOP {satName}.TA {satName}.TotalMass;");
                        sb.AppendLine($"Maneuver {bName}({satName});");
                        sb.AppendLine($"Report TrajReport {satName}.ElapsedSecs {satName}.X {satName}.Y {satName}.Z {satName}.VX {satName}.VY {satName}.VZ {satName}.{cBody}.Altitude {satName}.SMA {satName}.ECC {satName}.INC {satName}.RAAN {satName}.AOP {satName}.TA {satName}.TotalMass;");
                    }
                    else if (stype == "Equation" || stype == "Set") {
                        string vName = st.variable ?? "";
                        if (string.IsNullOrWhiteSpace(vName)) continue;
                        if (vName.Contains(".ThrustDirection")) continue; // Skip orphan ThrustDirection assignment steps
                        if (vName.Contains(".")) {
                            string stripped = GMATParameterRegistry.StripCraftPrefix(vName);
                            vName = $"{satName}.{stripped}";
                        }
                        sb.AppendLine($"{vName} = {st.expression};");
                    }
                    else if (stype == "Report") {
                        string sub = GMATParameterRegistry.SanitizeGmatIdentifier(!string.IsNullOrEmpty(st.subscriber_name) ? st.subscriber_name : $"StepReport_{i + 1}", $"StepReport_{i + 1}");
                        string standardReportCols = $"{satName}.ElapsedSecs {satName}.X {satName}.Y {satName}.Z {satName}.VX {satName}.VY {satName}.VZ {satName}.{cBody}.Altitude {satName}.SMA {satName}.ECC {satName}.INC {satName}.RAAN {satName}.AOP {satName}.TA {satName}.{cBody}.RMAG {satName}.TotalMass {satName}.DryMass";
                        string reportExpr = !string.IsNullOrWhiteSpace(st.expression) ? st.expression : standardReportCols;
                        sb.AppendLine($"% Step Report ({sub})");
                        sb.AppendLine($"Report {sub} {reportExpr};");
                    }
                    else if (stype == "Optimize") {
                        string opt = GMATParameterRegistry.SanitizeGmatIdentifier(!string.IsNullOrEmpty(st.optimizer_name) ? st.optimizer_name : "Yukon1", "Yukon1");
                        sb.AppendLine($"Optimize {opt} {{SolveMode = {st.solve_mode ?? "Solve"}, ExitMode = {st.exit_mode ?? "SaveAndContinue"}}};");
                    }
                    else if (stype == "Minimize") {
                        string opt = GMATParameterRegistry.SanitizeGmatIdentifier(!string.IsNullOrEmpty(st.optimizer_name) ? st.optimizer_name : "Yukon1", "Yukon1");
                        string minVar = !string.IsNullOrEmpty(st.minimize_variable) ? st.minimize_variable : "Sat.FuelMassBurned";
                        if (minVar.Contains(".")) minVar = $"{satName}.{GMATParameterRegistry.StripCraftPrefix(minVar)}";
                        sb.AppendLine($"   Minimize {opt}({minVar});");
                    }
                    else if (stype == "NonlinearConstraint") {
                        string opt = GMATParameterRegistry.SanitizeGmatIdentifier(!string.IsNullOrEmpty(st.optimizer_name) ? st.optimizer_name : "Yukon1", "Yukon1");
                        string lhs = !string.IsNullOrEmpty(st.constraint_lhs) ? st.constraint_lhs : "Sat.Earth.RMAG";
                        if (lhs.Contains(".")) lhs = $"{satName}.{GMATParameterRegistry.StripCraftPrefix(lhs)}";
                        string op = !string.IsNullOrEmpty(st.constraint_op) ? st.constraint_op : ">=";
                        string val = st.constraint_val.ToString("G", CultureInfo.InvariantCulture);
                        sb.AppendLine($"   NonlinearConstraint {opt}({lhs} {op} {val});");
                    }
                    else if (stype == "EndOptimize") {
                        sb.AppendLine("EndOptimize;");
                    }
                    else if (stype == "CustomScript") {
                        if (!string.IsNullOrWhiteSpace(st.custom_verbatim_script)) {
                            sb.AppendLine(st.custom_verbatim_script.TrimEnd());
                        }
                    }
                }
            }

            // Final Native Trajectory and Orbital Elements Report
            sb.AppendLine("% Trajectory & Orbital Parameters Report");
            sb.AppendLine($"Report TrajReport {satName}.ElapsedSecs {satName}.X {satName}.Y {satName}.Z {satName}.VX {satName}.VY {satName}.VZ {satName}.{cBody}.Altitude {satName}.SMA {satName}.ECC {satName}.INC {satName}.RAAN {satName}.AOP {satName}.TA {satName}.TotalMass;");

            return sb.ToString();
        }

        /// <summary>
        /// 单步代码透视生成器：就地生成指定 MissionStep 对应的 GMAT 原生脚本片段，供 GUI 代码透视查看。
        /// </summary>
        public static string GenerateStepScript(MissionStep st, string satName = null, string centralBody = null) {
            if (st == null) return "";
            string safeSat = !string.IsNullOrEmpty(satName) ? satName : GMATStateManager.Current.GetSpacecraftName();
            string safeBody = !string.IsNullOrEmpty(centralBody) ? centralBody : (GMATStateManager.Current.Spacecraft.CentralBody ?? "Earth");
            string stype = st.type;

            if (stype == "Propagate") {
                string pName = !string.IsNullOrEmpty(st.propagator) ? st.propagator : "LEOProp";
                string stopCond = FormatStopCondition(safeSat, safeBody, st);
                string backMod = st.is_backwards ? " Backwards" : "";
                return $"Propagate{backMod} {pName}({safeSat}) {{{stopCond}}};";
            }
            if (stype == "Target") {
                string dc = GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name ?? "DC", "DC");
                return $"Target {dc} {{SolveMode = {st.solve_mode ?? "Solve"}, ExitMode = {st.exit_mode ?? "SaveAndContinue"}}};";
            }
            if (stype == "EndTarget") {
                return "EndTarget;";
            }
            if (stype == "Optimize") {
                string opt = GMATParameterRegistry.SanitizeGmatIdentifier(!string.IsNullOrEmpty(st.optimizer_name) ? st.optimizer_name : "Yukon1", "Yukon1");
                return $"Optimize {opt} {{SolveMode = {st.solve_mode ?? "Solve"}, ExitMode = {st.exit_mode ?? "SaveAndContinue"}}};";
            }
            if (stype == "Minimize") {
                string opt = GMATParameterRegistry.SanitizeGmatIdentifier(!string.IsNullOrEmpty(st.optimizer_name) ? st.optimizer_name : "Yukon1", "Yukon1");
                string minVar = !string.IsNullOrEmpty(st.minimize_variable) ? st.minimize_variable : "Sat.FuelMassBurned";
                if (minVar.Contains(".")) minVar = $"{safeSat}.{GMATParameterRegistry.StripCraftPrefix(minVar)}";
                return $"Minimize {opt}({minVar});";
            }
            if (stype == "NonlinearConstraint") {
                string opt = GMATParameterRegistry.SanitizeGmatIdentifier(!string.IsNullOrEmpty(st.optimizer_name) ? st.optimizer_name : "Yukon1", "Yukon1");
                string lhs = !string.IsNullOrEmpty(st.constraint_lhs) ? st.constraint_lhs : "Sat.Earth.RMAG";
                if (lhs.Contains(".")) lhs = $"{safeSat}.{GMATParameterRegistry.StripCraftPrefix(lhs)}";
                string op = !string.IsNullOrEmpty(st.constraint_op) ? st.constraint_op : ">=";
                string val = st.constraint_val.ToString("G", CultureInfo.InvariantCulture);
                return $"NonlinearConstraint {opt}({lhs} {op} {val});";
            }
            if (stype == "EndOptimize") {
                return "EndOptimize;";
            }
            if (stype == "Vary") {
                string dc = GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name ?? "DC", "DC");
                string vVar = st.vary_variable ?? "";
                if (vVar.Contains(".")) vVar = $"{safeSat}.{GMATParameterRegistry.StripCraftPrefix(vVar)}";
                string init = !string.IsNullOrEmpty(st.vary_initial_str) ? st.vary_initial_str : st.vary_initial.ToString("G", CultureInfo.InvariantCulture);
                string pert = !string.IsNullOrEmpty(st.vary_perturbation_str) ? st.vary_perturbation_str : "0.0001";
                string low = !string.IsNullOrEmpty(st.vary_lower_str) ? st.vary_lower_str : st.vary_lower.ToString("G", CultureInfo.InvariantCulture);
                string up = !string.IsNullOrEmpty(st.vary_upper_str) ? st.vary_upper_str : st.vary_upper.ToString("G", CultureInfo.InvariantCulture);
                string step = !string.IsNullOrEmpty(st.vary_max_step_str) ? st.vary_max_step_str : "10";
                return $"Vary {dc}({vVar} = {init}, {{Perturbation = {pert}, Lower = {low}, Upper = {up}, MaxStep = {step}}});";
            }
            if (stype == "Achieve") {
                string dc = GMATParameterRegistry.SanitizeGmatIdentifier(st.dc_name ?? "DC", "DC");
                string rawGoal = st.achieve_param ?? "";
                string goalParam = GMATParameterRegistry.StripCraftPrefix(rawGoal);
                if (goalParam.Contains("=")) goalParam = GMATParameterRegistry.StripCraftPrefix(goalParam.Split('=')[0].Trim());
                if (!goalParam.Contains(".")) goalParam = $"{safeBody}.{goalParam}";
                string val = !string.IsNullOrEmpty(st.achieve_val_str) ? st.achieve_val_str : st.achieve_val.ToString("G", CultureInfo.InvariantCulture);
                string tol = !string.IsNullOrEmpty(st.achieve_tolerance_str) ? st.achieve_tolerance_str : "0.1";
                return $"Achieve {dc}({safeSat}.{goalParam} = {val}, {{Tolerance = {tol}}});";
            }
            if (stype == "FiniteBurn") {
                string fbName = GMATParameterRegistry.SanitizeGmatIdentifier(st.burn_name, "Finite1");
                string pName = !string.IsNullOrEmpty(st.propagator) ? st.propagator : "LEOProp";
                string dur = st.burn_use_vary_var ? (st.burn_vary_var_name ?? "") : (!string.IsNullOrEmpty(st.duration_str) ? st.duration_str : st.duration.ToString("G", CultureInfo.InvariantCulture));
                return $"BeginFiniteBurn {fbName}({safeSat});\nPropagate {pName}({safeSat}) {{{safeSat}.ElapsedSecs = {dur}}};\nEndFiniteBurn {fbName}({safeSat});";
            }
            if (stype == "ImpulsiveBurn" || stype == "Maneuver") {
                string bName = GMATParameterRegistry.SanitizeGmatIdentifier(st.burn_name ?? st.label, "Burn1");
                return $"Maneuver {bName}({safeSat});";
            }
            if (stype == "CustomScript") {
                return st.custom_verbatim_script ?? "";
            }
            if (stype == "Equation" || stype == "Set") {
                return $"{st.variable} = {st.expression};";
            }
            if (stype == "Report") {
                return $"Report {st.subscriber_name ?? "TrajReport"} {st.expression};";
            }
            return $"% Step: {st.label}";
        }

        private static string FormatStopCondition(string satName, string centralBody, MissionStep st) {
            if (st.stop_conditions != null && st.stop_conditions.Count > 0) {
                var formattedList = new List<string>();
                for (int i = 0; i < st.stop_conditions.Count; i++) {
                    var sc = st.stop_conditions[i];
                    string f = FormatSingleStopCondition(satName, centralBody, sc.parameter, sc.target_val_str, sc.target_val, st.duration, st.duration_str);
                    if (!string.IsNullOrEmpty(f)) formattedList.Add(f);
                }
                if (formattedList.Count > 0) {
                    return string.Join(", ", formattedList.ToArray());
                }
            }

            return FormatSingleStopCondition(satName, centralBody, st.stop_type, st.target_val_str, st.target_val, st.duration, st.duration_str);
        }

        private static string FormatSingleStopCondition(string satName, string centralBody, string rawCond, string rawValStr, double rawVal, double durNum, string durStr) {
            string cond = GMATParameterRegistry.StripCraftPrefix(rawCond ?? "").Trim();

            if (string.IsNullOrEmpty(cond)) {
                string dur = !string.IsNullOrEmpty(durStr) ? durStr : (durNum > 0 ? durNum.ToString("G", CultureInfo.InvariantCulture) : "3600.0");
                return $"{satName}.ElapsedSecs = {dur}";
            }

            // 1. If condition already contains an explicit '=', e.g. "Earth.Altitude = 200" or "ElapsedSecs = 3600"
            if (cond.Contains("=")) {
                var p = cond.Split('=');
                string lhs = GMATParameterRegistry.StripCraftPrefix(p[0].Trim());
                string rhs = p[1].Trim();
                if (!lhs.Contains(".") && !GMATParameterRegistry.IsSpacecraftDirectProperty(lhs)) {
                    lhs = $"{centralBody}.{lhs}";
                }
                return $"{satName}.{lhs} = {rhs}";
            }

            // 2. GMAT Built-in Extrema Events
            // Apoapsis and Periapsis in GMAT syntax can be {Sat.Earth.Apoapsis} or {Sat.Apoapsis}
            if (cond.EndsWith(".Apoapsis", StringComparison.OrdinalIgnoreCase)) {
                return $"{satName}.{cond}";
            }
            if (cond.Equals("Apoapsis", StringComparison.OrdinalIgnoreCase)) {
                return $"{satName}.{centralBody}.Apoapsis";
            }
            if (cond.EndsWith(".Periapsis", StringComparison.OrdinalIgnoreCase)) {
                return $"{satName}.{cond}";
            }
            if (cond.Equals("Periapsis", StringComparison.OrdinalIgnoreCase)) {
                return $"{satName}.{centralBody}.Periapsis";
            }

            // Equatorial Nodes in GMAT syntax are strictly: {Sat.Earth.Latitude = 0.0} or {Sat.EarthMJ2000Eq.Z = 0.0}
            if (cond.Equals("Node", StringComparison.OrdinalIgnoreCase) || cond.Equals("AN", StringComparison.OrdinalIgnoreCase) || cond.Equals("DN", StringComparison.OrdinalIgnoreCase) ||
                cond.EndsWith(".Node", StringComparison.OrdinalIgnoreCase) || cond.EndsWith(".AN", StringComparison.OrdinalIgnoreCase) || cond.EndsWith(".DN", StringComparison.OrdinalIgnoreCase)) {
                return $"{satName}.{centralBody}.Latitude = 0.0";
            }

            // 3. Elapsed Time Stop Conditions
            if (cond.Equals("Time", StringComparison.OrdinalIgnoreCase) || cond.Equals("ElapsedSecs", StringComparison.OrdinalIgnoreCase) || cond.EndsWith(".ElapsedSecs", StringComparison.OrdinalIgnoreCase)) {
                string durVal = !string.IsNullOrEmpty(rawValStr) ? rawValStr : (!string.IsNullOrEmpty(durStr) ? durStr : (rawVal > 0 ? rawVal.ToString("G", CultureInfo.InvariantCulture) : (durNum > 0 ? durNum.ToString("G", CultureInfo.InvariantCulture) : "3600.0")));
                return $"{satName}.ElapsedSecs = {durVal}";
            }
            if (cond.Equals("Days", StringComparison.OrdinalIgnoreCase) || cond.Equals("ElapsedDays", StringComparison.OrdinalIgnoreCase) || cond.EndsWith(".ElapsedDays", StringComparison.OrdinalIgnoreCase)) {
                string durVal = !string.IsNullOrEmpty(rawValStr) ? rawValStr : (!string.IsNullOrEmpty(durStr) ? durStr : (rawVal > 0 ? rawVal.ToString("G", CultureInfo.InvariantCulture) : (durNum > 0 ? (durNum / 86400.0).ToString("G", CultureInfo.InvariantCulture) : "1.0")));
                return $"{satName}.ElapsedDays = {durVal}";
            }

            // 4. Value-based Numerical Stop Conditions (e.g. Altitude, RMAG, Latitude, TA, RAAN, AOP, FPA, etc.)
            string rhsVal = !string.IsNullOrEmpty(rawValStr) ? rawValStr : rawVal.ToString("G", CultureInfo.InvariantCulture);
            if (!cond.Contains(".") && !GMATParameterRegistry.IsSpacecraftDirectProperty(cond)) {
                cond = $"{centralBody}.{cond}";
            }
            return $"{satName}.{cond} = {rhsVal}";
        }
    }
